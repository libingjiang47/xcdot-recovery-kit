let activeLocale = 'en';

export function normalizeLocale(locale) {
  const value = String(locale ?? '');
  if (value.toLowerCase().startsWith('zh')) return 'zh-CN';
  if (value.toLowerCase().startsWith('ja')) return 'ja';
  if (value.toLowerCase().startsWith('de')) return 'de';
  if (value.toLowerCase().startsWith('fr')) return 'fr';
  return 'en';
}

export function resolveLocale() {
  if (typeof localStorage !== 'undefined') {
    const saved = localStorage.getItem('xcdot.locale');
    if (saved && SUPPORTED_LOCALES.includes(saved)) return saved;
  }
  if (typeof navigator !== 'undefined') {
    for (const locale of navigator.languages ?? [navigator.language]) {
      const resolved = normalizeLocale(locale);
      if (resolved !== 'en' || String(locale).toLowerCase().startsWith('en')) return resolved;
    }
  }
  return 'en';
}

export function setLocale(locale, persist = true) {
  activeLocale = SUPPORTED_LOCALES.includes(locale) ? locale : normalizeLocale(locale);
  if (persist && typeof localStorage !== 'undefined')
    localStorage.setItem('xcdot.locale', activeLocale);
  return activeLocale;
}

export function getLocale() {
  return activeLocale;
}

export function htmlLanguage(locale = activeLocale) {
  return locale;
}

export function t(key, variables = {}) {
  const template = translations[activeLocale][key] ?? translations.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => String(variables[name] ?? `{${name}}`));
}
